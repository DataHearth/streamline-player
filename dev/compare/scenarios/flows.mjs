  r.libUpToNav = await focused();
  await key("ArrowRight");
  await key("Enter");
  await wait(2500);
  r.navToShows = [app.url(), await focused(), await text(".count")];
  // detail actions
  await app.goto("http://localhost:1420/detail/movies/2");
  await wait(3000);
  r.detailStart = await focused();
  await key("ArrowRight");
  r.detailRight = await focused();
  await key("Enter");
  await wait(1200);
  r.markWatched = [await focused(), await app.evaluate(() => document.body.innerText.match(/Marked as \w+/)?.[0] ?? null)];
