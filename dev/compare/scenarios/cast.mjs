export default async ({ app, shot, wait, key, focused }) => {
  const r = {};
  const cls = () => app.evaluate(() => document.activeElement?.className ?? "");
  await app.goto("http://localhost:1420/detail/movies/1");
  await wait(3000);
  r.castTitle = await app.evaluate(() => [...document.querySelectorAll(".more-title")].map((e) => e.innerText.replace(/\s+/g, " ")));
  await key("ArrowDown");
  r.down1 = [await focused(), await cls()];
  await wait(600);
  await shot("cast-movie");
  await key("ArrowRight", 2);
  r.right2 = await focused();
  await key("ArrowDown");
  r.downToSimilar = await cls();
  await key("ArrowUp");
  r.backUp = await focused();
  await key("Enter");
  await wait(2500);
  r.personPath = await app.evaluate(() => location.pathname);
  r.personFocus = await focused();
  await shot("person");
  r.personText = (await app.evaluate(() => document.body.innerText)).replace(/\s+/g, " ").slice(0, 500);
  await key("ArrowDown"); r.pDown = await focused();
  await key("ArrowDown"); r.pDown2 = await focused();
  await wait(600);
  await shot("person-low");
  await key("Escape"); await wait(1500);
  r.back = [await app.evaluate(() => location.pathname), await focused()];
  await app.goto("http://localhost:1420/detail/series/3");
  await wait(3000);
  r.seriesCast = await app.evaluate(() => [...document.querySelectorAll(".more-title")].map((e) => e.innerText.replace(/\s+/g, " ")).join(" | ") + " :: " + [...document.querySelectorAll(".cast-name")].map((e) => e.textContent).join(", "));
  await app.evaluate(() => [...document.querySelectorAll(".season")].find((b) => b.textContent.includes("1"))?.click());
  await wait(500);
  r.season1Cast = await app.evaluate(() => [...document.querySelectorAll(".more-title")].map((e) => e.innerText.replace(/\s+/g, " ")).join(" | ") + " :: " + [...document.querySelectorAll(".cast-name")].map((e) => e.textContent).join(", "));
  await app.evaluate(() => document.querySelector(".cast")?.scrollIntoView());
  await wait(500);
  await shot("cast-series");
  return r;
};
